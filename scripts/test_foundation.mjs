import assert from 'node:assert/strict';
const root = new URL('../src/utils/', import.meta.url).href;
const { encryptJSON, decryptJSON, isEncryptedEnvelope, WrongPassphraseError } = await import(root + 'crypto.ts');
const { planMerge, isExpiredTombstone, unionPrograms, DELETE_RETENTION_DAYS } = await import(root + 'merge.ts');
let n = 0; const ok = (name) => { n++; console.log('  pass', name); };

// --- crypto ---
const payload = { records: [{ id: 'a', name: 'Demo é中', icNumber: '000101-00-0001' }], n: 5 };
const env = await encryptJSON(payload, 'correct horse battery');
assert.ok(isEncryptedEnvelope(env)); ok('envelope shape');
assert.ok(!JSON.stringify(env).includes('Demo'), 'plaintext leaked'); ok('ciphertext hides names and IC');
assert.deepEqual(await decryptJSON(env, 'correct horse battery'), payload); ok('round trip incl. unicode');
await assert.rejects(() => decryptJSON(env, 'wrong passphrase'), WrongPassphraseError); ok('wrong passphrase rejected');
const tampered = { ...env, data: env.data.slice(0, -4) + (env.data.slice(-4) === 'AAAA' ? 'BBBB' : 'AAAA') };
await assert.rejects(() => decryptJSON(tampered, 'correct horse battery'), WrongPassphraseError); ok('tampered file rejected');
const env2 = await encryptJSON(payload, 'correct horse battery');
assert.notEqual(env.salt, env2.salt); assert.notEqual(env.iv, env2.iv); ok('fresh salt and iv every time');
await assert.rejects(() => decryptJSON({ ...env, iterations: 1 }, 'x'), /Unsupported/); ok('absurd iteration count refused');
const big = { records: Array.from({ length: 3000 }, (_, i) => ({ id: 'r' + i, name: 'P' + i, pad: 'x'.repeat(200) })) };
assert.deepEqual(await decryptJSON(await encryptJSON(big, 'pw-pw-pw-pw'), 'pw-pw-pw-pw'), big); ok('large payload (~700 KB)');

// --- merge ---
const R = (o) => ({ id: 'x', name: 'N', icNumber: '900101-01-1111', patientType: 'Existing', programs: ['ARV'], bloodInvestigations: [], createdAt: '2026-01-01T00:00:00.000Z', updatedAt: '2026-01-01T00:00:00.000Z', ...o });
let p = planMerge([R({ id: 'a' })], [R({ id: 'b', icNumber: '800202-02-2222', name: 'New' })]);
assert.equal(p.added, 1); assert.equal(p.toPut.length, 1); ok('new patient added');
p = planMerge([R({ id: 'a', name: 'Old', updatedAt: '2026-02-01T00:00:00.000Z' })], [R({ id: 'a', name: 'Newer', updatedAt: '2026-03-01T00:00:00.000Z' })]);
assert.equal(p.updated, 1); assert.equal(p.toPut[0].name, 'Newer'); ok('newer incoming wins');
p = planMerge([R({ id: 'a', name: 'Local newer', updatedAt: '2026-04-01T00:00:00.000Z' })], [R({ id: 'a', name: 'Stale', updatedAt: '2026-03-01T00:00:00.000Z' })]);
assert.equal(p.toPut.length, 0); assert.equal(p.unchanged, 1); ok('older incoming ignored');
p = planMerge([R({ id: 'a', icNumber: '900101-01-1111' })], [R({ id: 'zzz', icNumber: '900101011111', name: 'Same person', updatedAt: '2026-05-01T00:00:00.000Z' })]);
assert.equal(p.toPut.length, 1); assert.equal(p.toPut[0].id, 'a'); assert.equal(p.added, 0); ok('same IC (different format and id) merges into one patient, keeps local id');
const L = R({ id: 'a', updatedAt: '2026-06-01T00:00:00.000Z', programs: ['ARV'] });
const I = R({ id: 'a', updatedAt: '2026-05-01T00:00:00.000Z', programs: ['MMT'], mmt: { dispensing: 'Daily', doseHistory: [], doseLog: [], urineTests: [], takeHomes: [], reviews: [], updatedAt: '2026-05-01T00:00:00.000Z' } });
p = planMerge([L], [I]);
assert.deepEqual(p.toPut[0].programs, ['ARV', 'MMT']); assert.ok(p.toPut[0].mmt); ok('older record still contributes its MMT data and program');
const L2 = R({ id: 'a', updatedAt: '2026-07-01T00:00:00.000Z', programs: ['ARV', 'MMT'], mmt: { dispensing: 'Daily', currentDoseMg: 60, doseHistory: [], doseLog: [], urineTests: [], takeHomes: [], reviews: [], updatedAt: '2026-07-01T00:00:00.000Z' } });
const I2 = R({ id: 'a', updatedAt: '2026-08-01T00:00:00.000Z', programs: ['ARV', 'MMT'], mmt: { dispensing: 'Daily', currentDoseMg: 40, doseHistory: [], doseLog: [], urineTests: [], takeHomes: [], reviews: [], updatedAt: '2026-06-01T00:00:00.000Z' } });
p = planMerge([L2], [I2]);
assert.equal(p.toPut[0].mmt.currentDoseMg, 60); ok('MMT block chosen by its own timestamp');
const now = Date.parse('2026-11-16T00:00:00Z');
const day = 86400000;
const del = (daysAgo) => R({ id: 'd', deletedAt: new Date(now - daysAgo * day).toISOString(), updatedAt: new Date(now - daysAgo * day).toISOString() });
p = planMerge([R({ id: 'd', updatedAt: '2026-01-01T00:00:00.000Z' })], [del(2)], now);
assert.ok(p.toPut[0].deletedAt); ok('a delete on another device reaches this one');
p = planMerge([], [del(45)], now);
assert.equal(p.skipped, 1); assert.equal(p.toPut.length, 0); ok('expired deleted record is not resurrected');
assert.equal(isExpiredTombstone(del(DELETE_RETENTION_DAYS - 1), now), false);
assert.equal(isExpiredTombstone(del(DELETE_RETENTION_DAYS + 1), now), true); ok('30-day retention boundary');
const again = planMerge(p.toPut, p.toPut);
p = planMerge([L], [L]); assert.equal(p.toPut.length, 0); ok('merging identical data changes nothing (no sync ping-pong)');
p = planMerge([], [R({ id: 'a' }), R({ id: 'b', icNumber: '900101011111', updatedAt: '2026-09-01T00:00:00.000Z' })]);
assert.equal(p.toPut.length, 1); ok('duplicate people inside one backup collapse into one');
assert.deepEqual(unionPrograms(undefined, ['MMT']), ['ARV', 'MMT']); ok('missing programs default to ARV');
console.log(`\n${n} checks passed`);
